<h2>제1조 (목적)</h2>
<p>
	본 약관은 MediCraft Pro(이하 "회사")가 제공하는 의학용어 학습 모바일 웹앱(이하 "서비스")의 이용
	조건과 절차, 회사와 회원의 권리·의무를 규정함을 목적으로 합니다.
</p>

<h2>제2조 (정의)</h2>
<ul>
	<li>"회원"이란 본 약관에 동의하고 서비스를 이용하는 자를 말합니다.</li>
	<li>"계정"이란 회원 식별과 서비스 이용을 위해 부여된 고유 식별자(Google 계정 연동)를 말합니다.</li>
	<li>"콘텐츠"란 어근, 의학용어, 예시, 풀이 등 서비스에서 제공하는 학습 자료를 말합니다.</li>
</ul>

<h2>제3조 (약관의 효력 및 변경)</h2>
<ul>
	<li>본 약관은 회원이 동의함으로써 효력이 발생합니다.</li>
	<li>회사는 약관을 변경할 수 있으며, 변경 시 변경 내용을 서비스 내에서 공지합니다.</li>
	<li>변경된 약관에 동의하지 않는 회원은 회원 탈퇴를 요청할 수 있습니다.</li>
</ul>

<h2>제4조 (회원가입 및 계정 관리)</h2>
<ul>
	<li>회원가입은 만 14세 이상만 가능합니다.</li>
	<li>회원은 Google OAuth를 통해 가입하며, 본인의 계정 정보를 안전하게 관리할 책임이 있습니다.</li>
	<li>타인의 계정을 도용하거나 부정 사용해서는 안 됩니다.</li>
</ul>

<h2>제5조 (서비스 제공)</h2>
<ul>
	<li>회사는 어근 친숙화·용어 디코딩 학습 도구, 진척도 추적, 어근 도감 등을 제공합니다.</li>
	<li>회사는 서비스 개선·점검·장애 등을 이유로 서비스 일부를 변경·중단할 수 있습니다.</li>
	<li>학습 콘텐츠는 의학용어 학습을 돕기 위한 것이며, 의학적 자문·진단·치료를 대체하지 않습니다.</li>
</ul>

<h2>제6조 (회원의 의무)</h2>
<ul>
	<li>회원은 관계 법령과 본 약관, 공지사항을 준수해야 합니다.</li>
	<li>회사 또는 제3자의 지적재산권을 침해하거나, 콘텐츠를 무단 복제·배포해서는 안 됩니다.</li>
	<li>서비스 운영을 방해하는 행위(자동화 도구·과도한 요청·역공학 등)를 해서는 안 됩니다.</li>
</ul>

<h2>제7조 (콘텐츠 및 지적재산권)</h2>
<ul>
	<li>서비스 내 콘텐츠의 저작권은 회사 또는 적법한 출처에 귀속됩니다.</li>
	<li>일부 콘텐츠는 NBK(NCBI Bookshelf) OER 등 CC-BY 라이선스 자료를 기반으로 하며, 해당 출처를 표기합니다.</li>
	<li>회원은 학습 목적의 개인 사용을 넘어 콘텐츠를 상업적으로 이용해서는 안 됩니다.</li>
</ul>

<h2>제8조 (회원 탈퇴)</h2>
<ul>
	<li>회원은 언제든 설정에서 회원 탈퇴를 요청할 수 있습니다.</li>
	<li>탈퇴 시 회원의 개인정보 및 학습 기록은 개인정보 처리방침에 따라 파기됩니다.</li>
</ul>

