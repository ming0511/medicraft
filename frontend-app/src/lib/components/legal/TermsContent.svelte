<ul>
	<li>회사는 천재지변, 통신 장애 등 회사의 귀책사유가 없는 사유로 인한 서비스 중단에 대해 책임지지 않습니다.</li>
	<li>서비스에서 제공하는 학습 콘텐츠의 의학적 정확성에 대한 최종 판단 책임은 회원에게 있으며, 회사는 콘텐츠를 출처 대조·검수하여 합리적 정확성을 유지하기 위해 노력합니다.</li>
</ul>

